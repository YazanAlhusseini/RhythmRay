def generate_report(scan_type: str, diagnosis: str, confidence) -> str:
    if scan_type == "CXR":
        if diagnosis == "No Finding":
            note = CXR_CLINICAL.get("No Finding", "Normal chest X-ray.")
        else:
            labels = [l.strip() for l in diagnosis.split("+")]
            notes = [CXR_CLINICAL.get(l, f"Finding: {l}") for l in labels]
            note = " | ".join(notes)
    else:
        labels = [l.strip() for l in diagnosis.split("+")]
        notes = [ECG_CLINICAL.get(l, f"Finding: {l}") for l in labels]
        note = " | ".join(notes)

    prompt = f"""### Instruction:
You are a medical AI assistant. Based on the AI analysis result below,
write a concise clinical report in 3-4 sentences for the physician.

Scan Type: {scan_type}
AI Diagnosis: {diagnosis}
Max Confidence: {confidence}%
Clinical Notes: {note}

### Response:
"""
    inputs = tokenizer(prompt, return_tensors="pt").to(medgemma.device)
    with torch.no_grad():
        out = medgemma.generate(
            **inputs,
            max_new_tokens=150,
            temperature=0.3,
            do_sample=True,
            pad_token_id=tokenizer.eos_token_id
        )
    resp = tokenizer.decode(out[0], skip_special_tokens=True)
    return resp.split("### Response:")[-1].strip() \
           if "### Response:" in resp else resp

