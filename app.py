def analyze_full(image_path: str = None, signal_file=None, scan_type: str = "ECG") -> dict:
    if scan_type == "CXR":
        result = predict_cxr(image_path)
    else:

        if signal_file is not None:
            signal = load_signal_file(signal_file)
            if signal is not None:
                result = predict_ecg(signal)
            else:
                result = ("Error", 0, {})
        elif image_path is not None:
            signal = ecg_image_to_signal(image_path)
            if signal is not None:
                result = predict_ecg(signal)
            else:
                result = ("Error", 0, {})
        else:
            result = ("Error", 0, {})

    report = generate_report(scan_type, result[0], result[1])

    return {
        "scan_type" : scan_type,
        "diagnosis" : result[0],
        "confidence": result[1],
        "all_probs" : result[2],
        "report"    : report
    }

