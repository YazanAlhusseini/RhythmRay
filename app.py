from PIL import Image
import pickle

CXR_LABELS = [
    'Cardiomegaly', 'Hernia', 'Infiltration', 'Nodule', 'Emphysema',
    'Effusion', 'Atelectasis', 'Pleural_Thickening', 'Pneumothorax',
    'Mass', 'Fibrosis', 'Consolidation', 'Edema', 'Pneumonia'
]

def preprocess_cxr(image_path):
    # 1. Convert to Grayscale
    img = Image.open(image_path).convert('L')
    img = img.resize((224, 224))

    img = np.array(img).astype(np.float32)

    # 2. EXACT torchxrayvision normalization ([-1024, 1024] range)
    img = (img / 255.0) * 2048.0 - 1024.0

    # 3. Add Channel and Batch dimensions
    img = np.expand_dims(img, axis=0)  # -> (1, 224, 224)
    img = np.expand_dims(img, axis=0)  # -> (1, 1, 224, 224)

    return torch.from_numpy(img).float()

def load_cxr_model():
    """Load PyTorch CXR model."""
    if not os.path.exists(CXR_CKPT):
        raise FileNotFoundError(f"CXR model not found: {CXR_CKPT}")

    print(f"⏳ Loading CXR model from: {CXR_CKPT}")

    device_map = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    cxr_data = torch.load(CXR_CKPT, map_location=device_map, weights_only=False)

    # 1. Extract the model/state_dict and classes
    if isinstance(cxr_data, tuple) and len(cxr_data) == 2:
        model = cxr_data[0]
        class_names = cxr_data[1] if cxr_data[1] else CXR_LABELS
    elif isinstance(cxr_data, dict):
        # Check if it's a wrapper dict, otherwise assume the dict IS the state_dict
        if 'model' in cxr_data:
            model = cxr_data['model']
        elif 'state_dict' in cxr_data:
            model = cxr_data['state_dict']
        else:
            model = cxr_data # It's a raw state_dict!

        class_names = cxr_data.get('classes', CXR_LABELS)
    else:
        model = cxr_data
        class_names = CXR_LABELS


    if isinstance(model, dict):
        from torchvision import models
        import torch.nn as nn

        architecture = models.densenet121(pretrained=False)

        architecture.features.conv0 = nn.Conv2d(1, 64, kernel_size=(7, 7), stride=(2, 2), padding=(3, 3), bias=False)

        num_classes = len(CXR_LABELS)
        architecture.classifier = nn.Linear(architecture.classifier.in_features, num_classes)

        clean_state_dict = {}
        for k, v in model.items():
            clean_key = k.replace('module.', '').replace('backbone.', '')
            clean_state_dict[clean_key] = v

        architecture.load_state_dict(clean_state_dict, strict=False)
        model = architecture

    model.eval()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = model.to(device)

    print(f"✅ CXR model loaded on {device}")
    return model, class_names

def predict_cxr(image_path):
    """Predict with PyTorch CXR model."""
    model, class_names = load_cxr_model()
    img = preprocess_cxr(image_path).to(next(model.parameters()).device)

    with torch.no_grad():
        logits = model(img)
        probs = torch.sigmoid(logits).cpu().numpy()[0]

    thresholds = [0.5] * len(class_names)
    preds = np.array([1 if probs[i] >= thresholds[i] else 0 for i in range(len(class_names))])
    detected = [class_names[i] for i, p in enumerate(preds) if p == 1]

    if not detected:
        detected = [class_names[np.argmax(probs)]]

    main_diag = " + ".join(detected)
    max_conf = max(probs[i] * 100 for i in [class_names.index(d) for d in detected])
    all_probs = {class_names[i]: round(float(probs[i]) * 100, 1) for i in range(len(class_names))}

    return main_diag, round(float(max_conf), 1), all_probs

