SUPERCLASSES = ["NORM", "MI", "STTC", "CD", "HYP"]

def load_ecg_resnet1d():
    """Load our PTB-XL ResNet1D model."""
    if not os.path.exists(ECG_CKPT):
        raise FileNotFoundError(f"ResNet1D model not found: {ECG_CKPT}")

    model = tf.keras.models.load_model(ECG_CKPT, compile=False)


    thresholds = [0.5] * 5
    if os.path.exists(THRESHOLD_CKPT):
        import json
        with open(THRESHOLD_CKPT, 'r') as f:
            t = json.load(f)
            thresholds = [t.get(cls, 0.5) for cls in SUPERCLASSES]

    return model, thresholds

def ecg_image_to_signal(image_path, target_length=5000):
    """Convert ECG image to 12-lead signal (same digitizer as original)."""
    img = cv2.imread(image_path)
    if img is None:
        return None

    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)


    mask_r1 = cv2.inRange(hsv, (0, 50, 50), (10, 255, 255))
    mask_r2 = cv2.inRange(hsv, (170, 50, 50), (180, 255, 255))
    mask_blue = cv2.inRange(hsv, (90, 30, 150), (130, 255, 255))
    grid_mask = cv2.bitwise_or(cv2.bitwise_or(mask_r1, mask_r2), mask_blue)

    clean = gray.copy()
    clean[grid_mask > 0] = 255
    clean = cv2.equalizeHist(clean)

    _, binary = cv2.threshold(clean, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (2, 2))
    binary = cv2.morphologyEx(binary, cv2.MORPH_OPEN, kernel)


    row_h = h // 3
    col_w = w // 4
    leads_coords = [
        (r * row_h, (r + 1) * row_h, c * col_w, (c + 1) * col_w)
        for r in range(3) for c in range(4)
    ]

    def extract_lead(binary_img, y1, y2, x1, x2):
        region = binary_img[y1:y2, x1:x2]
        rh, rw = region.shape
        baseline = rh / 2
        signal = np.zeros(rw)
        for col in range(rw):
            px = np.where(region[:, col] > 0)[0]
            if len(px) > 0:
                signal[col] = baseline - np.average(px, weights=region[:, col][px].astype(float))
        if signal.std() > 1e-6:
            signal = (signal - signal.mean()) / signal.std()
        signal_resized = cv2.resize(signal.reshape(1, -1).astype(np.float32), (target_length, 1)).flatten()
        return signal_resized

    def butter_lowpass(data, cutoff=40, fs=500, order=4):
        try:
            nyq = 0.5 * fs
            b, a = butter(order, cutoff / nyq, btype="low", analog=False)
            return filtfilt(b, a, data)
        except:
            return data

    ecg_12 = np.zeros((12, target_length), dtype=np.float32)
    for i, (y1, y2, x1, x2) in enumerate(leads_coords[:12]):
        ecg_12[i] = butter_lowpass(extract_lead(binary, y1, y2, x1, x2))

    return ecg_12

def load_signal_file(uploaded_file, target_length=5000):
    """Load signal from .npy or .csv files."""
    fname = uploaded_file.name.lower()

    if fname.endswith(".npy"):
        import io
        signal = np.load(io.BytesIO(uploaded_file.getvalue()))

        if signal.ndim == 3 and signal.shape[0] == 1:
            signal = signal.squeeze(0)
    elif fname.endswith(".csv"):
        import pandas as pd
        signal = pd.read_csv(uploaded_file).values
    else:
        return None


    if signal.ndim == 2 and signal.shape[0] != 12:
        signal = signal.T

    signal = signal[:12, :target_length].astype(np.float32)
    if signal.shape[1] < target_length:
        pad = np.zeros((12, target_length - signal.shape[1]), dtype=np.float32)
        signal = np.hstack([signal, pad])


    for i in range(12):
        mean = signal[i].mean()
        std = signal[i].std()
        if std > 0:
            signal[i] = (signal[i] - mean) / std

    return signal

def predict_ecg(signal_12lead):
    """Predict with CNN."""
    model, thresholds = load_ecg_resnet1d()


    x = np.transpose(signal_12lead, (1, 0))
    x = np.expand_dims(x, axis=0).astype(np.float32)

    # Predict
    probs = model.predict(x, verbose=0)[0]

    # Apply thresholds
    preds = np.array([1 if probs[i] >= thresholds[i] else 0 for i in range(5)])

    # Get detected classes
    detected = [SUPERCLASSES[i] for i, p in enumerate(preds) if p == 1]
    if not detected:
        detected = [SUPERCLASSES[np.argmax(probs)]]

    main_diag = " + ".join(detected)
    max_conf = max(probs[i] * 100 for i in [SUPERCLASSES.index(d) for d in detected])

    all_probs = {SUPERCLASSES[i]: round(float(probs[i]) * 100, 1) for i in range(5)}

    return main_diag, round(float(max_conf), 1), all_probs

